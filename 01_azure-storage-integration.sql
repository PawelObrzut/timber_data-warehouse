	AZURE_TENANT_ID = '128722ca-fda2-437d-9552-3437472f5f09'
	ENABLED = TRUE
	STORAGE_ALLOWED_LOCATIONS = (
		'azure://sttimber001.blob.core.windows.net/landing/'
	);

