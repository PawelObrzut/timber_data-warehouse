--- =======
--- PIPES are for semi-automatic ingress of data. Here, however, pipes are set to auto_ingest which means there is no need of invoking pipes explicitely.
--- semi-automatic also means it does not scan blob continuesly but relies on notification received from cloud storage provider.
--- =======
CREATE PIPE IF NOT EXISTS ANAPLAN_RMCPNL
	AUTO_INGEST = TRUE
	INTEGRATION = 'TIMBER_AZURE_NOTIFICATION'
AS
COPY INTO WOODWORKS_DB.BRONZE.ANAPLAN_RMCPNL
FROM @WOODWORKS_DB.BRONZE.AZURE_TIMBER_STAGE/ANAPLAN_RMCPNL/
	FILE_FORMAT = (FORMAT_NAME = 'WOODWORKS_DB.BRONZE.TIMBER_CSV_FORMAT')
	MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

