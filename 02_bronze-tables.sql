USE DATABASE WOODWORKS_DB;
USE SCHEMA BRONZE;
USE WAREHOUSE WOODWORKS_WH;

--- ===============
--- This project is based on 8 data sources. Hence, 8 tables will structure data for future transformations.
--- all files within a source folder in azure has identical structure thus we can use INFER_SCHEMA
--- ===============
CREATE TABLE IF NOT EXISTS ANAPLAN_RMCPNL
USING TEMPLATE (
    SELECT ARRAY_AGG(
        OBJECT_CONSTRUCT(
            'COLUMN_NAME', COLUMN_NAME,
            'TYPE', 'VARCHAR',
            'NULLABLE', TRUE,
            'ORDER_ID', ORDER_ID
        )
    ) WITHIN GROUP (ORDER BY ORDER_ID)
    FROM TABLE(
        INFER_SCHEMA(
            LOCATION => '@WOODWORKS_DB.BRONZE.AZURE_TIMBER_STAGE/ANAPLAN_RMCPNL/',
            FILE_FORMAT => 'WOODWORKS_DB.BRONZE.TIMBER_CSV_FORMAT'
        )
    )
);

