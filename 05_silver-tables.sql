USE DATABASE WOODWORKS_DB;
USE SCHEMA SILVER;
USE WAREHOUSE WOODWORKS_WH;

--- ===============
--- Create Silver layer TABLES that assign appropriate data types like DATE, NUMBER, BOOLEAN or VARCHAR
--- ===============

CREATE OR REPLACE PROCEDURE WOODWORKS_DB.SILVER.SP_REFRESH_SILVER()
    RETURNS VARCHAR
    LANGUAGE SQL
    EXECUTE AS OWNER
    AS
    $$
    BEGIN
        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.ANAPLAN_RMCPNL AS
        SELECT
            TRIM(PROFIT_CTR) AS PROFIT_CTR,
            TRY_TO_DATE('01/' || NULLIF(TRIM(PERIOD), ''),'DD/MM/YYYY') AS PERIOD,
            TRY_TO_NUMBER(NULLIF(TRIM(YEAR), ''), 4, 0) AS YEAR,
            TRY_TO_NUMBER(NULLIF(TRIM(MONTH), ''), 2, 0) AS MONTH,
            UPPER(TRIM(FUNC_AREA)) AS FUNC_AREA,
            UPPER(TRIM(COST_CATEGORY)) AS COST_CATEGORY,
            TRY_TO_DECIMAL(NULLIF(TRIM(COST_AMOUNT), ''), 18, 2) AS COST_AMOUNT,
            UPPER(TRIM(CURRENCY)) AS CURRENCY,
            UPPER(TRIM(VERSION)) AS VERSION,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ETL_TIMESTAMP), ''),'YYYY-MM-DD HH24:MI:SS') AS ETL_TIMESTAMP
        FROM WOODWORKS_DB.BRONZE.ANAPLAN_RMCPNL;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.DELIVERY_NOTES AS
        SELECT
            TRIM(DELIVERY_NOTE_NO) AS DELIVERY_NOTE_NO,
            TRIM(PLANT_NO) AS PLANT_NO,
            TRY_TO_DATE(NULLIF(TRIM(DELIVERY_DATE), ''),'YYYY-MM-DD') AS DELIVERY_DATE,
            TRIM(CUSTOMER_NO) AS CUSTOMER_NO,
            TRIM(CONTRACT_NO) AS CONTRACT_NO,
            TRIM(ARTICLE_NO) AS ARTICLE_NO,
            TRIM(PRODUCT_NO) AS PRODUCT_NO,
            TRIM(TIMBER_SPECIFICATION_NO) AS TIMBER_SPECIFICATION_NO,
            TRIM(TIMBER_SPECIFICATION_DESCRIPTION) AS TIMBER_SPECIFICATION_DESCRIPTION,
            TRY_TO_DECIMAL(NULLIF(TRIM(DELIVERY_AMOUNT), ''),18, 3) AS DELIVERY_AMOUNT,
            UPPER(TRIM(INCOTERM_1)) AS INCOTERM_1,
            TRIM(SHIP_TO_NR) AS SHIP_TO_NR,
            TRY_TO_BOOLEAN(NULLIF(TRIM(DN_ANNULATION), '')) AS DN_ANNULATION,

            TRIM(SERVICE_ARTICLE_1) AS SERVICE_ARTICLE_1,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_1), ''), 18, 3) AS SERVICE_QUANTITY_1,

            TRIM(SERVICE_ARTICLE_2) AS SERVICE_ARTICLE_2,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_2), ''), 18, 3) AS SERVICE_QUANTITY_2,

            TRIM(SERVICE_ARTICLE_3) AS SERVICE_ARTICLE_3,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_3), ''), 18, 3) AS SERVICE_QUANTITY_3,

            TRIM(SERVICE_ARTICLE_4) AS SERVICE_ARTICLE_4,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_4), ''), 18, 3) AS SERVICE_QUANTITY_4,

            TRIM(SERVICE_ARTICLE_5) AS SERVICE_ARTICLE_5,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_5), ''), 18, 3) AS SERVICE_QUANTITY_5,

            TRIM(SERVICE_ARTICLE_6) AS SERVICE_ARTICLE_6,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_6), ''), 18, 3) AS SERVICE_QUANTITY_6,

            TRIM(SERVICE_ARTICLE_7) AS SERVICE_ARTICLE_7,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_7), ''), 18, 3) AS SERVICE_QUANTITY_7,

            TRIM(SERVICE_ARTICLE_8) AS SERVICE_ARTICLE_8,
            TRY_TO_DECIMAL(NULLIF(TRIM(SERVICE_QUANTITY_8), ''), 18, 3) AS SERVICE_QUANTITY_8,

            UPPER(TRIM(PRODUCT_FAMILY)) AS PRODUCT_FAMILY,
            TRIM(PRODUCT_DESCRIPTION) AS PRODUCT_DESCRIPTION,
            TRIM(PRODUCT_SKU) AS PRODUCT_SKU,
            TRIM(SERVICE_DESCRIPTION_1) AS SERVICE_DESCRIPTION_1,
            TRIM(SERVICE_DESCRIPTION_2) AS SERVICE_DESCRIPTION_2,
            TRIM(SERVICE_DESCRIPTION_3) AS SERVICE_DESCRIPTION_3,
            TRIM(SERVICE_DESCRIPTION_4) AS SERVICE_DESCRIPTION_4,
            TRIM(SERVICE_DESCRIPTION_5) AS SERVICE_DESCRIPTION_5,
            TRIM(SERVICE_DESCRIPTION_6) AS SERVICE_DESCRIPTION_6,
            TRIM(SERVICE_DESCRIPTION_7) AS SERVICE_DESCRIPTION_7,
            TRIM(SERVICE_DESCRIPTION_8) AS SERVICE_DESCRIPTION_8,
            UPPER(TRIM(CARRIER_TYPE)) AS CARRIER_TYPE,
            TRIM(CARRIER_NAME) AS CARRIER_NAME
        FROM WOODWORKS_DB.BRONZE.DELIVERY_NOTES;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.MIXDESIGN_COST_DAILY AS
        SELECT
            TRIM(PLANT_NO) AS PLANT_NO,
            TRIM(SAP_NO) AS SAP_NO,
            TRIM(MIXDESIGN_NO) AS MIXDESIGN_NO,
            TRY_TO_DATE(NULLIF(TRIM(COST_DATE), ''),'YYYY-MM-DD') AS COST_DATE,
            TRY_TO_DECIMAL(NULLIF(TRIM(COST), ''), 18, 2) AS COST,
            UPPER(TRIM(CURRENCY)) AS CURRENCY,
            UPPER(TRIM(PRODUCT_FAMILY)) AS PRODUCT_FAMILY,
            TRIM(PRODUCT_DESCRIPTION) AS PRODUCT_DESCRIPTION
        FROM WOODWORKS_DB.BRONZE.MIXDESIGN_COST_DAILY;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.SAP_CASH_CONTRACT AS
        SELECT
            TRIM(CONTRACT_NO) AS CONTRACT_NO,
            TRIM(MATERIAL) AS MATERIAL,
            TRY_TO_DECIMAL(NULLIF(TRIM(PRICE_PER_UNIT), ''),18, 2) AS PRICE_PER_UNIT,
            UPPER(TRIM(CURRENCY)) AS CURRENCY,
            UPPER(TRIM(CONTRACT_TYPE)) AS CONTRACT_TYPE,
            TRY_TO_DATE(NULLIF(TRIM(VALID_FROM), ''), 'YYYY-MM-DD') AS VALID_FROM,
            TRY_TO_DATE(NULLIF(TRIM(VALID_TO), ''), 'YYYY-MM-DD') AS VALID_TO,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ETL_TIMESTAMP), ''),'YYYY-MM-DD HH24:MI:SS') AS ETL_TIMESTAMP,
            TRIM(CONTRACT_NAME) AS CONTRACT_NAME,
            TRIM(MATERIAL_DESCRIPTION) AS MATERIAL_DESCRIPTION
        FROM WOODWORKS_DB.BRONZE.SAP_CASH_CONTRACT;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.SAP_INV_COST AS
        SELECT
            TRIM(COST_DOCUMENT_NO) AS COST_DOCUMENT_NO,
            TRIM(DELIVERY_NOTE_NO) AS DELIVERY_NOTE_NO,
            TRIM(PLANT_NO) AS PLANT_NO,
            UPPER(TRIM(SERVICE_TYPE)) AS SERVICE_TYPE,
            TRY_TO_DATE(NULLIF(TRIM(COST_DATE), ''),'YYYY-MM-DD') AS COST_DATE,
            TRY_TO_DECIMAL(NULLIF(TRIM(COST_AMOUNT), ''),18, 2) AS COST_AMOUNT,
            UPPER(TRIM(CURRENCY)) AS CURRENCY,
            UPPER(TRIM(CARRIER_TYPE)) AS CARRIER_TYPE,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ETL_TIMESTAMP), ''),'YYYY-MM-DD HH24:MI:SS') AS ETL_TIMESTAMP
        FROM WOODWORKS_DB.BRONZE.SAP_INV_COST;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.SAP_INV_REV AS
        SELECT
            TRIM(DELIVERY_NOTE_NO) AS DELIVERY_NOTE_NO,
            TRIM(PLANT_NO) AS PLANT_NO,
            TRIM(MATERIAL) AS MATERIAL,
            TRIM(INVOICE_NO) AS INVOICE_NO,
            TRY_TO_DATE(NULLIF(TRIM(INVOICE_DATE), ''),'YYYY-MM-DD') AS INVOICE_DATE,
            TRY_TO_DECIMAL(NULLIF(TRIM(NET_VALUE), ''),18, 2) AS NET_VALUE,
            UPPER(TRIM(CURRENCY)) AS CURRENCY,
            TRY_TO_DECIMAL(NULLIF(TRIM(QUANTITY), ''),18, 3) AS QUANTITY,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ETL_TIMESTAMP), ''),'YYYY-MM-DD HH24:MI:SS') AS ETL_TIMESTAMP,
            TRIM(MATERIAL_DESCRIPTION) AS MATERIAL_DESCRIPTION,
            UPPER(TRIM(REVENUE_CATEGORY)) AS REVENUE_CATEGORY,
            TRY_TO_DECIMAL(NULLIF(TRIM(UNIT_PRICE), ''),18, 2) AS UNIT_PRICE
        FROM WOODWORKS_DB.BRONZE.SAP_INV_REV;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.SF_ACCOUNT AS
        SELECT
            TRIM(ID) AS ID,
            TRIM(NAME) AS NAME,
            UPPER(TRIM(RECORD_TYPE)) AS RECORD_TYPE,
            TRIM(SAP_NUMBER__C) AS SAP_NUMBER__C,
            TRIM(PARENTID) AS PARENTID,
            TRIM(BILLING_CITY) AS BILLING_CITY,
            TRIM(BILLING_COUNTRY) AS BILLING_COUNTRY,
            TRIM(SHIPPING_CITY) AS SHIPPING_CITY,
            TRIM(SHIPPING_COUNTRY) AS SHIPPING_COUNTRY,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(LASTMODIFIEDDATE), ''),'YYYY-MM-DD HH24:MI:SS') AS LASTMODIFIEDDATE,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ETL_TIMESTAMP), ''),'YYYY-MM-DD HH24:MI:SS') AS ETL_TIMESTAMP
        FROM WOODWORKS_DB.BRONZE.SF_ACCOUNT;

        CREATE OR REPLACE TABLE WOODWORKS_DB.SILVER.SF_SUBSCRIPTION AS
        SELECT
            TRIM(ID) AS ID,
            TRIM(CONTRACTSAPNUMBER__C) AS CONTRACTSAPNUMBER__C,
            TRIM(PRODUCT_CODE__C) AS PRODUCT_CODE__C,
            TRY_TO_DECIMAL(NULLIF(TRIM(UNIT_PRICE__C), ''),18, 2) AS UNIT_PRICE__C,
            UPPER(TRIM(CURRENCYISOCODE)) AS CURRENCYISOCODE,
            TRY_TO_DATE(NULLIF(TRIM(START_DATE__C), ''),'YYYY-MM-DD') AS START_DATE__C,
            TRY_TO_DATE(NULLIF(TRIM(END_DATE__C), ''),'YYYY-MM-DD') AS END_DATE__C,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(LASTMODIFIEDDATE), ''),'YYYY-MM-DD HH24:MI:SS') AS LASTMODIFIEDDATE,
            TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ETL_TIMESTAMP), ''),'YYYY-MM-DD HH24:MI:SS') AS ETL_TIMESTAMP,
            TRIM(PRODUCT_DESCRIPTION__C) AS PRODUCT_DESCRIPTION__C,
            TRIM(CONTRACT_NAME__C) AS CONTRACT_NAME__C
        FROM WOODWORKS_DB.BRONZE.SF_SUBSCRIPTION;
        
        RETURN 'Silver layer refreshed successfully.'; 
    END;
    $$;

CALL WOODWORKS_DB.SILVER.SP_REFRESH_SILVER();

SHOW TABLES;