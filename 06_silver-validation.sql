USE DATABASE WOODWORKS_DB;
USE SCHEMA SILVER;
USE WAREHOUSE WOODWORKS_WH;

-- =========================================================
-- 06 - SILVER VALIDATION
-- Purpose:
--   Validate row counts, nulls and conversion issues
--   after Bronze -> Silver transformation.
--
-- This script is READ-ONLY.
-- It does not modify any data.
-- =========================================================

-- =========================================================
-- 1. ROW COUNT VALIDATION
-- Compare Bronze and Silver table row counts.
-- =========================================================


SELECT 'ANAPLAN_RMCPNL' AS TABLE_NAME,
       (SELECT COUNT(*) FROM BRONZE.ANAPLAN_RMCPNL) AS BRONZE_ROWS,
       (SELECT COUNT(*) FROM SILVER.ANAPLAN_RMCPNL) AS SILVER_ROWS

UNION ALL

SELECT 'DELIVERY_NOTES',
       (SELECT COUNT(*) FROM BRONZE.DELIVERY_NOTES),
       (SELECT COUNT(*) FROM SILVER.DELIVERY_NOTES)

UNION ALL

SELECT 'MIXDESIGN_COST_DAILY',
       (SELECT COUNT(*) FROM BRONZE.MIXDESIGN_COST_DAILY),
       (SELECT COUNT(*) FROM SILVER.MIXDESIGN_COST_DAILY)

UNION ALL

SELECT 'SAP_CASH_CONTRACT',
       (SELECT COUNT(*) FROM BRONZE.SAP_CASH_CONTRACT),
       (SELECT COUNT(*) FROM SILVER.SAP_CASH_CONTRACT)

UNION ALL

SELECT 'SAP_INV_COST',
       (SELECT COUNT(*) FROM BRONZE.SAP_INV_COST),
       (SELECT COUNT(*) FROM SILVER.SAP_INV_COST)

UNION ALL

SELECT 'SAP_INV_REV',
       (SELECT COUNT(*) FROM BRONZE.SAP_INV_REV),
       (SELECT COUNT(*) FROM SILVER.SAP_INV_REV)

UNION ALL

SELECT 'SF_ACCOUNT',
       (SELECT COUNT(*) FROM BRONZE.SF_ACCOUNT),
       (SELECT COUNT(*) FROM SILVER.SF_ACCOUNT)

UNION ALL

SELECT 'SF_SUBSCRIPTION',
       (SELECT COUNT(*) FROM BRONZE.SF_SUBSCRIPTION),
       (SELECT COUNT(*) FROM SILVER.SF_SUBSCRIPTION)

ORDER BY TABLE_NAME;

-- =========================================================
-- 2. NULL VALIDATION
-- Check important fields for missing values in Silver.
-- =========================================================

SELECT
    'ANAPLAN_RMCPNL' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(PERIOD IS NULL) AS NULL_PERIOD,
    COUNT_IF(PROFIT_CTR IS NULL) AS NULL_PROFIT_CTR,
    COUNT_IF(COST_AMOUNT IS NULL) AS NULL_COST_AMOUNT
FROM SILVER.ANAPLAN_RMCPNL;

SELECT
    'DELIVERY_NOTES' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(DELIVERY_NOTE_NO IS NULL) AS NULL_DELIVERY_NOTE_NO,
    COUNT_IF(DELIVERY_DATE IS NULL) AS NULL_DELIVERY_DATE,
    COUNT_IF(PLANT_NO IS NULL) AS NULL_PLANT_NO
FROM SILVER.DELIVERY_NOTES;

SELECT
    'MIXDESIGN_COST_DAILY' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(PLANT_NO IS NULL) AS NULL_PLANT_NO,
    COUNT_IF(COST_DATE IS NULL) AS NULL_COST_DATE,
    COUNT_IF(COST IS NULL) AS NULL_COST
FROM SILVER.MIXDESIGN_COST_DAILY;

SELECT
    'SAP_CASH_CONTRACT' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(CONTRACT_NO IS NULL) AS NULL_CONTRACT_NO,
    COUNT_IF(VALID_FROM IS NULL) AS NULL_VALID_FROM,
    COUNT_IF(VALID_TO IS NULL) AS NULL_VALID_TO
FROM SILVER.SAP_CASH_CONTRACT;

SELECT
    'SAP_INV_COST' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(COST_DATE IS NULL) AS NULL_COST_DATE,
    COUNT_IF(COST_AMOUNT IS NULL) AS NULL_COST_AMOUNT,
    COUNT_IF(DELIVERY_NOTE_NO IS NULL) AS NULL_DELIVERY_NOTE_NO
FROM SILVER.SAP_INV_COST;

SELECT
    'SAP_INV_REV' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(INVOICE_DATE IS NULL) AS NULL_INVOICE_DATE,
    COUNT_IF(NET_VALUE IS NULL) AS NULL_NET_VALUE,
    COUNT_IF(QUANTITY IS NULL) AS NULL_QUANTITY
FROM SILVER.SAP_INV_REV;

SELECT
    'SF_ACCOUNT' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(ID IS NULL) AS NULL_ID,
    COUNT_IF(NAME IS NULL) AS NULL_NAME
FROM SILVER.SF_ACCOUNT;

SELECT
    'SF_SUBSCRIPTION' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(ID IS NULL) AS NULL_ID,
    COUNT_IF(START_DATE__C IS NULL) AS NULL_START_DATE,
    COUNT_IF(END_DATE__C IS NULL) AS NULL_END_DATE
FROM SILVER.SF_SUBSCRIPTION;